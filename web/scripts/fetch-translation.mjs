// One-shot: fetch the pinned English translation (Saheeh International). Run from repo root:
// node web/scripts/fetch-translation.mjs
import { mkdirSync, writeFileSync } from 'node:fs';
import surahsData from '../src/data/surahs.json' with { type: 'json' };

const EDITION = 'eng-safiurrahmanalm';
const COMMIT = '47ca096b0976443ba2eab2e45cdf0fb4096a2610';
const BASE = `https://cdn.jsdelivr.net/gh/fawazahmed0/quran-api@${COMMIT}/editions/${EDITION}`;
const OUT = new URL('../src/data/translation-en/', import.meta.url);
const TOTAL = 6236;
const DELAY_MS = 120;

const surahs = surahsData.surahs;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function fetchChapter(id) {
  let lastError;
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      const res = await fetch(`${BASE}/${id}.json`);
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      return await res.json();
    } catch (err) {
      lastError = err;
      if (attempt < 3) await sleep(DELAY_MS * attempt * 4);
    }
  }
  throw new Error(`surah ${id}: failed after 3 attempts: ${lastError?.message}`);
}

mkdirSync(OUT, { recursive: true });

const index = [];
let total = 0;
const rows = [];

for (const surah of surahs) {
  const payload = await fetchChapter(surah.id);
  const chapter = payload?.chapter;
  if (!Array.isArray(chapter)) throw new Error(`surah ${surah.id}: missing chapter array`);
  if (chapter.length !== surah.ayahCount) {
    throw new Error(`surah ${surah.id}: ${chapter.length} verses, expected ${surah.ayahCount}`);
  }

  const ayahs = chapter.map((entry, i) => {
    if (entry.verse !== i + 1) {
      throw new Error(`surah ${surah.id}: verse ${entry.verse} at position ${i + 1}`);
    }
    const text = typeof entry.text === 'string' ? entry.text : '';
    if (!text.trim()) throw new Error(`surah ${surah.id}:${entry.verse} empty text`);
    return { n: entry.verse, t: text };
  });

  writeFileSync(new URL(`${surah.id}.json`, OUT), JSON.stringify({ surah: surah.id, ayahs }));
  for (const a of ayahs) index.push({ s: surah.id, a: a.n, t: a.t });
  total += ayahs.length;
  rows.push(`  ${surah.id}: ${ayahs.length} ✓`);
  await sleep(DELAY_MS);
}

if (total !== TOTAL) throw new Error(`total ${total}, expected ${TOTAL}`);
if (index.length !== TOTAL) throw new Error(`search index ${index.length}, expected ${TOTAL}`);

writeFileSync(new URL('../search-index-en.json', OUT), JSON.stringify({ ayahs: index }));

writeFileSync(
  new URL('SOURCE.md', OUT),
  `# English translation source

- Edition: \`${EDITION}\` (Saheeh International)
- Pinned commit: \`${COMMIT}\`
- URL template: \`${BASE}/<surah>.json\`
- Fetched: 2026-10-24
- The upstream project's own terms apply — verify the translation license before commercial/store use.

Generated by \`web/scripts/fetch-translation.mjs\`; never hand-edit the JSON files.
`,
);

console.log(`OK: 114 surahs, ${total} ayahs`);
console.log(rows.join('\n'));
