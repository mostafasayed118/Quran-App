// One-shot: split the pinned Pickthall aggregate into per-surah files + the EN search index.
// Run from repo root: node web/scripts/fetch-translation.mjs
//
// One request instead of 114: jsDelivr rate-limits the per-surah fan-out (HTTP 403), and the
// aggregate is the exact file the app catalog pins (same SHA-256).
import { mkdirSync, writeFileSync } from 'node:fs';
import surahsData from '../src/data/surahs.json' with { type: 'json' };

const EDITION = 'eng-mohammedmarmadu';
const NAME = 'The Meaning of the Glorious Koran — Marmaduke Pickthall (1930)';
const COMMIT = '47ca096b0976443ba2eab2e45cdf0fb4096a2610';
const MIN_URL = `https://cdn.jsdelivr.net/gh/fawazahmed0/quran-api@${COMMIT}/editions/${EDITION}.min.json`;
const RAW_URL = `https://raw.githubusercontent.com/fawazahmed0/quran-api/${COMMIT}/editions/${EDITION}.min.json`;
const OUT = new URL('../src/data/translation-en/', import.meta.url);
const TOTAL = 6236;

const surahs = surahsData.surahs;

async function fetchAggregate() {
  let lastError;
  for (const url of [MIN_URL, RAW_URL]) {
    try {
      const res = await fetch(url);
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const json = await res.json();
      if (!Array.isArray(json?.quran)) throw new Error('missing quran array');
      return json;
    } catch (error) {
      lastError = error;
    }
  }
  throw new Error(`aggregate fetch failed: ${lastError?.message}`);
}

mkdirSync(OUT, { recursive: true });

const aggregate = await fetchAggregate();
const index = [];
let total = 0;
const rows = [];

for (const surah of surahs) {
  const entries = aggregate.quran.filter((row) => row.chapter === surah.id);
  if (entries.length !== surah.ayahCount) {
    throw new Error(`surah ${surah.id}: ${entries.length} verses, expected ${surah.ayahCount}`);
  }
  const ayahs = entries.map((entry, i) => {
    if (entry.verse !== i + 1) {
      throw new Error(`surah ${surah.id}: verse ${entry.verse} at position ${i + 1}`);
    }
    const text = typeof entry.text === 'string' ? entry.text : '';
    if (!text.trim()) throw new Error(`surah ${surah.id}:${entry.verse} empty text`);
    return { n: entry.verse, t: text };
  });

  writeFileSync(new URL(`${surah.id}.json`, OUT), JSON.stringify({ surah: surah.id, ayahs }));
  for (const a of ayahs) index.push({ s: surah.id, a: a.n, t: a.t });
  total += ayahs.length;
  rows.push(`  ${surah.id}: ${ayahs.length} ✓`);
}

if (total !== TOTAL) throw new Error(`total ${total}, expected ${TOTAL}`);
if (index.length !== TOTAL) throw new Error(`search index ${index.length}, expected ${TOTAL}`);

writeFileSync(new URL('../search-index-en.json', OUT), JSON.stringify({ ayahs: index }));

writeFileSync(
  new URL('SOURCE.md', OUT),
  `# English translation source

- Edition: \`${EDITION}\` — ${NAME}
- Pinned commit: \`${COMMIT}\`
- Aggregate: \`${MIN_URL}\` (fallback: raw.githubusercontent.com at the same commit)
- Fetched: 2026-10-24
- Pickthall's translation text is public domain (the translator died in 1936; the work was
  published in 1930). The digitized edition is used under its source's non-commercial terms;
  this site is free and ad-free and attributes the source.

Generated by \`web/scripts/fetch-translation.mjs\` (split from the pinned aggregate); never
hand-edit the JSON files.
`,
);

console.log(`OK: 114 surahs, ${total} ayahs`);
console.log(rows.join('\n'));
